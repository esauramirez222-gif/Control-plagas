/** Reemplaza <span data-icon="x"> por el SVG correspondiente dentro de un contenedor. */
function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    el.outerHTML = Icon(el.getAttribute('data-icon'));
  });
}
